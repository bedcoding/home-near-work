/** 탭 안 칸: 전세 대출, 보증보험, 월세 지원, 계약 전 확인 */
export type SupportSectionId = 'loan' | 'guard' | 'rent' | 'check';
/** 비교 표 칸에 쓰는 제도 항목 */
export type SupportColumnKey = 'who' | 'income' | 'amount' | 'cost';

export interface SupportSource {
  title: string;
  url: string;
  /** 자료 날짜(게시일, 보도일, 시행일). 모르면 빈 글자 */
  date: string;
}

export interface SupportProgram {
  id: string;
  section: Exclude<SupportSectionId, 'check'>;
  name: string;
  /** 운영 기관(접수처) */
  operator: string;
  /** open 운영 중, now 지금 접수 중(기간 있음), period 모집 기간에만 받고 지금은 아님, closed 신규 접수 끝, check 지금 조건이나 운영 여부 확인 필요 */
  status: 'open' | 'now' | 'period' | 'closed' | 'check';
  /** 이름 옆 표시(늘 받는 제도면 비움) */
  statusText?: string;
  /** 접힌 줄에 보이는 한 줄 설명 */
  oneLine: string;
  /** 비교 표 칸: 대상, 소득, 한도, 지원액, 금리, 보증료 */
  who?: string;
  income?: string;
  amount?: string;
  cost?: string;
  /** 펼치면 보이는 조건 표 [항목, 내용] */
  rows: [string, string][];
  /** 최근에 바뀐 것, 주의할 것, 확인 못 한 것 */
  notes: string[];
  apply: { label: string; url: string };
  sources: SupportSource[];
}

/** 계약 전 확인 칸의 공공 도구와 절차 */
export interface SupportTool {
  name: string;
  /** 언제 쓰는지(계약 전, 계약할 때, 입주하는 날 등) */
  when: string;
  what: string;
  url: string;
  urlLabel: string;
  /** 함께 보는 두 번째 링크 */
  more?: { label: string; url: string };
  /** 링크가 안내 화면이 아닐 때 따로 붙이는 근거 */
  source?: SupportSource;
  /** 자세한 순서가 있는 탭 안 칸 */
  toSection?: SupportSectionId;
}

/** '대출 받는 순서'와 '보험 되는지 먼저 확인하는 순서'의 한 단계. links는 그 단계에서 쓰는 공식 화면, toSection은 같이 볼 탭 안 칸 */
export interface SupportStep {
  /** 언제 할 일인지(계약 전, 잔금 날 등) */
  when: string;
  title: string;
  text: string;
  links?: { label: string; url: string }[];
  toSection?: SupportSectionId;
}

